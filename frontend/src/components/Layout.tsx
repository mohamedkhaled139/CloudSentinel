import { useState, type ReactNode } from "react";
import { NavLink, Outlet, useLocation } from "react-router-dom";
import {
  Activity,
  BarChart3,
  FlaskConical,
  LayoutDashboard,
  LogOut,
  Menu,
  Monitor as MonitorIcon,
  Moon,
  Network,
  Plug,
  Server,
  Settings,
  ShieldAlert,
  Siren,
  Sun,
} from "lucide-react";
import { useAuth } from "../lib/auth";
import { useOverview, useSystemInfo } from "../lib/hooks";
import { applyTheme, getTheme, type Theme } from "../lib/theme";

const NAV: { to: string; label: string; icon: ReactNode }[] = [
  { to: "/", label: "Overview", icon: <LayoutDashboard size={16} /> },
  { to: "/services", label: "Services", icon: <Server size={16} /> },
  { to: "/topology", label: "Topology", icon: <Network size={16} /> },
  { to: "/monitoring", label: "Monitoring", icon: <Activity size={16} /> },
  { to: "/incidents", label: "Incidents", icon: <Siren size={16} /> },
  { to: "/risks", label: "Risk intelligence", icon: <ShieldAlert size={16} /> },
  { to: "/reports", label: "Reports", icon: <BarChart3 size={16} /> },
  { to: "/integrations", label: "Integrations", icon: <Plug size={16} /> },
  { to: "/settings", label: "Settings", icon: <Settings size={16} /> },
];

export function Logo({ size = 26 }: { size?: number }) {
  return (
    <svg width={size} height={size} viewBox="0 0 32 32" aria-hidden>
      <rect width="32" height="32" rx="7" fill="#12312f" />
      <path d="M16 5l9 4v6c0 6-4 10.5-9 12-5-1.5-9-6-9-12V9z" fill="none" stroke="#3fd0b6" strokeWidth="2.2" strokeLinejoin="round" />
      <path d="M11 16.5h3l1.5-3 2.5 6 1.5-3H22" fill="none" stroke="#e8f6f3" strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round" />
    </svg>
  );
}

export function Layout() {
  const { user } = useAuth();
  const overview = useOverview();
  const system = useSystemInfo();
  const [open, setOpen] = useState(false);
  const location = useLocation();
  const openIncidents = overview.data?.open_incidents.length ?? 0;

  return (
    <div className="shell">
      <aside className={`sidebar ${open ? "open" : ""}`} aria-label="Main navigation">
        <div className="brand">
          <Logo />
          <div>
            CloudSentinel
            <small>Infrastructure health</small>
          </div>
        </div>
        {NAV.map((n) => (
          <NavLink
            key={n.to}
            to={n.to}
            end={n.to === "/"}
            className={({ isActive }) => `nav-link ${isActive ? "active" : ""}`}
            onClick={() => setOpen(false)}
          >
            {n.icon}
            {n.label}
            {n.to === "/incidents" && openIncidents > 0 && <span className="count">{openIncidents}</span>}
          </NavLink>
        ))}
        <div className="spacer" />
        <div className="foot">
          <div>{user?.email}</div>
          <div style={{ textTransform: "capitalize" }}>{user?.role}</div>
          <div className="mono" style={{ marginTop: 4 }}>v{system.data?.version ?? "…"}</div>
        </div>
      </aside>
      <div className="main">
        {(overview.data?.demo_mode || overview.data?.contains_synthetic_data) && (
          <div className="demo-banner" role="note">
            <FlaskConical size={14} aria-hidden />
            <span>
              <strong>Demo environment.</strong> Items marked <em>Synthetic</em> are simulated data generated by
              CloudSentinel's demo mode and do not describe real infrastructure.
            </span>
          </div>
        )}
        <Outlet context={{ setOpen, path: location.pathname } satisfies ShellContext} />
      </div>
    </div>
  );
}

export function PageHeader({
  title,
  subtitle,
  actions,
  setOpen,
}: {
  title: string;
  subtitle?: ReactNode;
  actions?: ReactNode;
  setOpen?: (v: boolean) => void;
}) {
  return (
    <header className="topbar">
      <button className="btn ghost icon-btn menu-toggle" aria-label="Open menu" onClick={() => setOpen?.(true)}>
        <Menu size={18} />
      </button>
      <div className="title">
        <h1>{title}</h1>
        {subtitle && <p>{subtitle}</p>}
      </div>
      {actions}
      <ShellButtons />
    </header>
  );
}

function ShellButtons() {
  const { logout } = useAuth();
  const [theme, setTheme] = useState<Theme>(getTheme());
  const next: Theme = theme === "system" ? "dark" : theme === "dark" ? "light" : "system";
  return (
    <>
      <button
        className="btn ghost icon-btn"
        title={`Theme: ${theme} (switch to ${next})`}
        aria-label={`Theme: ${theme}. Switch to ${next}`}
        onClick={() => {
          setTheme(next);
          applyTheme(next);
        }}
      >
        {theme === "light" ? <Sun size={16} /> : theme === "dark" ? <Moon size={16} /> : <MonitorIcon size={16} />}
      </button>
      <button className="btn ghost icon-btn" title="Sign out" aria-label="Sign out" onClick={() => void logout()}>
        <LogOut size={16} />
      </button>
    </>
  );
}

export interface ShellContext {
  setOpen: (v: boolean) => void;
  path: string;
}
